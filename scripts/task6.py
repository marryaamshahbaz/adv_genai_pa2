from tqdm.auto import tqdm

def generate_dataset(model_name, checkpoint, prompts, filename):
    output_path = OUT / filename

    if output_path.exists():
        with open(output_path) as f:
            results = json.load(f)
    else:
        results = []

    if len(results) > len(prompts):
        raise ValueError("Saved output has more rows than the prompt set")

    for i, row in enumerate(results):
        if (
            str(row["id"]) != str(prompts[i]["id"])
            or row["instruction"] != prompts[i]["instruction"]
        ):
            raise ValueError("Saved responses don't match the current prompts")

    print(f"\nModel: {model_name}")
    print("Already completed:", len(results))
    print("Remaining:", len(prompts) - len(results))

    if len(results) == len(prompts):
        return results

    model, tokenizer = load_model(checkpoint)

    try:
        for row in tqdm(prompts[len(results):], initial=len(results),
                        total=len(prompts)):

            response = generate_response(
                model,
                tokenizer,
                row["instruction"]
            )

            results.append({
                "id": row["id"],
                "instruction": row["instruction"],
                "response": response
            })

            with open(output_path, "w") as f:
                json.dump(results, f, indent=2)

    finally:
        unload_model(model)

    print("Saved:", output_path)
    return results

