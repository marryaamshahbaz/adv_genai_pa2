def find_checkpoint(folder):
    folder = Path(folder)

    candidates = [folder]
    if folder.exists():
        candidates += [p for p in folder.rglob("config.json")]

    for candidate in candidates:
        path = candidate if candidate.is_dir() else candidate.parent

        has_config = (path / "config.json").exists()
        has_weights = (
            any(path.glob("*.safetensors"))
            or any(path.glob("pytorch_model*.bin"))
        )

        if has_config and has_weights:
            return path

    raise FileNotFoundError(f"No loadable checkpoint found in {folder}")


