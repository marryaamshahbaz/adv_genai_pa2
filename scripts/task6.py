import random

def make_pairs(sft_rows, dpo_rows, prefix):
    assert len(sft_rows) == len(dpo_rows)

    rng = random.Random(42)
    pairs = []
    mappings = []

    for i, (sft, dpo) in enumerate(zip(sft_rows, dpo_rows)):
        assert sft["instruction"] == dpo["instruction"]

        pair_id = f"{prefix}-{i:04d}"
        sft_first = rng.choice([True, False])

        response_a = sft["response"] if sft_first else dpo["response"]
        response_b = dpo["response"] if sft_first else sft["response"]

        pairs.append({
            "id": pair_id,
            "instruction": sft["instruction"],
            "response_a": response_a,
            "response_b": response_b
        })

        mappings.append({
            "id": pair_id,
            "model_a": "sft" if sft_first else "dpo",
            "model_b": "dpo" if sft_first else "sft"
        })

    pairs_path = OUT / f"{prefix}_pairs.jsonl"
    mapping_path = OUT / f"{prefix}_mapping.jsonl"

    with open(pairs_path, "w") as f:
        for row in pairs:
            f.write(json.dumps(row) + "\n")

    with open(mapping_path, "w") as f:
        for row in mappings:
            f.write(json.dumps(row) + "\n")

    print(prefix, "- pairs:", len(pairs))
    return pairs, mappings

