def extract_prompts(data):
    if not isinstance(data, list):
        raise ValueError("Expected a JSON list of prompts")

    results = []

    for i, row in enumerate(data):
        if isinstance(row, str):
            instruction = row
            prompt_id = str(i)
        else:
            instruction = row.get("instruction", row.get("prompt"))
            prompt_id = str(row.get("id", i))

        if not isinstance(instruction, str) or not instruction.strip():
            raise ValueError(f"Invalid prompt at index {i}")

        results.append({
            "id": prompt_id,
            "instruction": instruction
        })

    return results

